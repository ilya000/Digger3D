#!/usr/bin/env node --experimental-strip-types
// Builds the game's asset bundle out of the Digger Remastered data.
//
// The data we ship comes from Digger Remastered (GPL-2, see README). In a few
// places Remastered differs from the 1983 program it was made from, and this
// project wants the 1983 behaviour, so those places are corrected. This tool
// compares the two - it needs `src/assets/original.ts`, produced locally by
// `tools/extract` from a copy of DIGGER.COM - and writes:
//
//   src/assets/corrections.ts   the corrections, as data
//   docs/ASSETS.md              the same list in a table, for people
//
//   node --experimental-strip-types tools/assets/build-assets.mjs
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");

const { originalBundle } = await import(resolve(ROOT, "src/assets/fromOriginal.ts"));
const { remasteredAssets: remastered } = await import(resolve(ROOT, "src/assets/fromRemastered.ts"));
const original = originalBundle();

/** Walks the sprite set and yields [path, spriteFromEach]. */
function* sprites(a, b, path = []) {
  if (Array.isArray(a)) {
    for (let i = 0; i < a.length; i++) yield* sprites(a[i], b[i], [...path, String(i)]);
    return;
  }
  if (a && a.color && a.opaque) {
    yield [path.join("."), a, b];
    return;
  }
  if (a && typeof a === "object") {
    for (const k of Object.keys(a)) yield* sprites(a[k], b[k], [...path, k]);
  }
}

const spritePatches = {};
const spriteReport = [];
for (const [path, mine, theirs] of sprites(original.sprites, remastered.sprites)) {
  const n = Math.min(mine.color.length, theirs.color.length);
  const patch = [];
  for (let i = 0; i < n; i++)
    if (mine.color[i] !== theirs.color[i] || mine.opaque[i] !== theirs.opaque[i])
      patch.push(i, mine.color[i], mine.opaque[i]);
  if (patch.length) {
    spritePatches[path] = patch;
    spriteReport.push({ path, pixels: patch.length / 3, size: `${mine.w}x${mine.h}` });
  }
}

const titlePatch = [];
for (let i = 0; i < original.title.length; i++)
  if (original.title[i] !== remastered.title[i]) titlePatch.push(i, original.title[i]);

const fontRemove = Object.keys(remastered.font).filter((k) => !(k in original.font));
const fontAdd = Object.keys(original.font).filter((k) => !(k in remastered.font));
const fontPatches = {};
for (const k of Object.keys(original.font))
  if (k in remastered.font) {
    const a = original.font[k].pixels, b = remastered.font[k].pixels;
    const patch = [];
    for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) patch.push(i, a[i]);
    if (patch.length) fontPatches[k] = patch;
  }
if (fontAdd.length) throw new Error(`the original has glyphs Remastered lacks: ${fontAdd}`);

const list = (a) => `[${a.join(",")}]`;
const ts = `// GENERATED by tools/assets/build-assets.mjs - do not edit.
//
// The game data of Digger Remastered (see src/assets/fromRemastered.ts) with the
// places where it differs from the 1983 original put back. Digger Remastered is
// under the GNU GPL v2, which is what lets us change it; every change is listed
// here and, in words, in docs/ASSETS.md.
//
// A sprite correction is a flat list of (index, colour, opaque) triples, a title
// correction a list of (index, colour) pairs, both into the arrays of the
// bundle; \`fontRemove\` names glyphs Remastered added that the original has not.

export const corrections = {
  /** Sprite path inside the bundle -> (index, colour, opaque)... */
  sprites: {
${Object.entries(spritePatches).map(([k, v]) => `    ${JSON.stringify(k)}: ${list(v)},`).join("\n")}
  } as Record<string, number[]>,
  /** The title picture: (index, colour)... */
  title: ${list(titlePatch)} as number[],
  /** Glyphs the original does not have. */
  fontRemove: ${JSON.stringify(fontRemove)} as string[],
  /** Glyph -> (index, colour)... */
  font: {
${Object.entries(fontPatches).map(([k, v]) => `    ${JSON.stringify(k)}: ${list(v)},`).join("\n")}
  } as Record<string, number[]>,
};
`;
writeFileSync(resolve(ROOT, "src/assets/corrections.ts"), ts);

const md = `# The game data: what comes from where

Everything the game draws and plays comes from **Digger Remastered**
([github.com/sobomax/digger](https://github.com/sobomax/digger)), which is under
the GNU GPL v2 and which carries the artwork, the font, the level maps and the
sound tables of the 1983 original inside it. That licence is what allows this
project to use that data and to change it, as long as the changes are stated.

This page is that statement. It is generated by \`tools/assets/build-assets.mjs\`,
which compares the Remastered data with the 1983 program byte by byte.

## Taken from Digger Remastered unchanged

| what | state |
|---|---|
| the 8 level maps | identical |
| the CGA palettes | identical |
| every sprite except those below | identical |
| the font, except the glyph below | identical |
| the tunes, the jingle, the emerald scale, the PIT constants (\`src/sound/data.ts\`) | identical |

## Changed, to match the 1983 original

| what | change | size |
|---|---|---|
${spriteReport.map((s) => `| sprite \`${s.path}\` | ${s.pixels} pixel${s.pixels === 1 ? "" : "s"} | ${s.size} |`).join("\n")}
| the title picture | ${titlePatch.length / 2} pixels of 64,000 | 320x200 |
| the font | ${fontRemove.length ? `the glyph ${fontRemove.map((c) => `\`${c}\``).join(", ")} removed` : "unchanged"} | 12x12 |

Why each of them:

* **fireball and explosion.** In the original these frames are 15-byte blocks
  that the game draws as 16, so a stray pixel from the following mask appears at
  the edge. Remastered removed it; we put it back.
* **the life icons.** The original's spare-life icons have no mask of their own;
  Remastered gave them one.
* **the title picture.** Remastered draws its title as a VGA picture, so it has
  no CGA one; ours starts as that picture halved and is corrected back to the
  320x200 screen the original shows. With the corrections applied the title is
  pixel-for-pixel the screenshot of the 1983 game (0 of 64,000 pixels differ).
* **the colon.** Remastered's font has one; the original's font has no colon at
  all, which is why the game never prints one.

The corrections themselves are in \`src/assets/corrections.ts\` as plain numbers,
and \`src/assets/game.ts\` applies them.
`;
writeFileSync(resolve(ROOT, "docs/ASSETS.md"), md);

console.log(`sprites corrected: ${spriteReport.length}`);
for (const s of spriteReport) console.log(`  ${s.path}: ${s.pixels} px (${s.size})`);
console.log(`title pixels corrected: ${titlePatch.length / 2}`);
console.log(`glyphs removed: ${fontRemove.join(", ") || "none"}`);
console.log(`corrections.ts: ${(ts.length / 1024).toFixed(1)} KB`);
